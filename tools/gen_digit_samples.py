#!/usr/bin/env python3
"""Turns the UCI "Pen-Based Recognition of Handwritten Digits" files into
src/core/DigitSamples.inc, the digit samples compiled into Scrible.

Usage: tools/gen_digit_samples.py pendigits.tra pendigits.tes > src/core/DigitSamples.inc

Get the files from https://doi.org/10.24432/C5MG6K (CC BY 4.0). Each row is 8 points
along the pen's path, spaced evenly by length, as x,y pairs scaled to 0..100 (y up),
then the digit.
"""
import sys


def rows(path):
    with open(path) as f:
        for line in f:
            values = [int(v) for v in line.replace(" ", "").strip().split(",") if v != ""]
            if len(values) != 17 or not all(0 <= v <= 100 for v in values[:16]) or not 0 <= values[16] <= 9:
                raise SystemExit(f"{path}: unexpected row {line!r}")
            yield values


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    train, test = list(rows(sys.argv[1])), list(rows(sys.argv[2]))
    print("// Generated by tools/gen_digit_samples.py from the UCI \"Pen-Based Recognition of")
    print("// Handwritten Digits\" dataset: E. Alpaydin & F. Alimoglu, UCI Machine Learning")
    print("// Repository, https://doi.org/10.24432/C5MG6K, licensed CC BY 4.0.")
    print(f"// {len(train)} samples by 30 writers, then {len(test)} by 14 others; each is")
    print("// x0,y0,...,x7,y7 (0..100, y up), digit.")
    print(f"constexpr size_t kDigitTrainCount = {len(train)};")
    print(f"constexpr uint8_t kDigitSamples[{len(train) + len(test)}][17] = {{")
    for r in train + test:
        print("{" + ",".join(map(str, r)) + "},")
    print("};")


main()
